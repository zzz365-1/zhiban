let pass = 0;
let fail = 0;
let canaryViolated = false;

for (const c of CASES) {
  const result = extractNotice(c.text);

  // 按用例声明了哪些字段决定比哪些字段。
  // 只有 expected 就只比地点，老用例行为不变。
  // 只有 expectedDate 就只比日期。两个都有就两个都比，全中才算通过。
  const checks = [];
  if ("expected" in c) {
    checks.push({ field: "地点", actual: result.location, want: c.expected });
  }
  if ("expectedDate" in c) {
    checks.push({ field: "日期", actual: result.deadline, want: c.expectedDate });
  }

  const eq = checks.every((ch) => ch.actual === ch.want);

  // mustFail 用例：期望不相等。相等才是异常。
  const ok = c.mustFail ? !eq : eq;

  if (ok) pass++;
  else {
    fail++;
    if (c.mustFail) canaryViolated = true;
  }

  console.log((ok ? "✓ " : "✗ ") + c.name);
  for (const ch of checks) {
    const wantStr = ch.want === null ? "(空)" : ch.want;
    const gotStr = ch.actual === null ? "(空)" : ch.actual;
    console.log("    " + ch.field + " 期望：" + wantStr);
    console.log("    " + ch.field + " 实际：" + gotStr);
  }

  if (!ok) {
    const snippet = c.text.slice(0, 60).split(LF).join(" ");
    console.log("    原文：" + snippet + " …");
  }
}

console.log("");
console.log("结果：" + pass + " 通过 / " + fail + " 失败 / 共 " + CASES.length + " 条");

